-- Защита от случайного совпадения фиксированных ID с чужим сценарием.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM scenario_knowledge k
        JOIN seed_interview_10 s ON s.knowledge_id = k.id
        WHERE k.scenario_id <> 'interview'
    ) OR EXISTS (
        SELECT 1 FROM interview_questions q
        JOIN seed_interview_10 s ON s.question_id = q.id
        WHERE q.scenario_id <> 'interview'
    ) THEN
        RAISE EXCEPTION 'ID набора уже используется в другом сценарии. Импорт отменён.';
    END IF;
END;
$$;

INSERT INTO scenario_knowledge
    (id, scenario_id, keywords, context, priority, enabled, version)
SELECT knowledge_id, 'interview', keywords, context, 10, true, 1
FROM seed_interview_10
ON CONFLICT (id) DO NOTHING;

INSERT INTO interview_questions
    (id, scenario_id, text, topic, difficulty,
     reference_answer, required_points, common_errors, version, enabled)
SELECT question_id, 'interview', question, topic, 'basic',
       context, required_points, common_errors, 1, true
FROM seed_interview_10
ON CONFLICT (id) DO NOTHING;

INSERT INTO interview_question_knowledge (question_id, knowledge_id)
SELECT question_id, knowledge_id
FROM seed_interview_10
ON CONFLICT (question_id, knowledge_id) DO NOTHING;

-- Количество записей именно этого набора. Дополнительные материалы сохраняются.
SELECT 'scenario_knowledge' AS entity, count(*) AS seed_records
FROM scenario_knowledge WHERE id IN (SELECT knowledge_id FROM seed_interview_10)
UNION ALL
SELECT 'interview_questions', count(*)
FROM interview_questions WHERE id IN (SELECT question_id FROM seed_interview_10)
UNION ALL
SELECT 'interview_question_knowledge', count(*)
FROM interview_question_knowledge l
JOIN seed_interview_10 s
  ON s.question_id = l.question_id AND s.knowledge_id = l.knowledge_id;

COMMIT;
